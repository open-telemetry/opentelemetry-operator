// Command gen-component-docs writes the list of collector components that the
// operator has specific support for, taken from the parsers in internal/components.
package main

import (
	"fmt"
	"os"
	"slices"
	"strings"

	"github.com/open-telemetry/opentelemetry-operator/internal/components"
	"github.com/open-telemetry/opentelemetry-operator/internal/components/exporters"
	"github.com/open-telemetry/opentelemetry-operator/internal/components/extensions"
	"github.com/open-telemetry/opentelemetry-operator/internal/components/processors"
	"github.com/open-telemetry/opentelemetry-operator/internal/components/receivers"
)

const outputPath = "docs/reference/collector-components.md"

const header = `# Collector components

<!-- This file is generated by 'make component-docs' from hack/gen-component-docs. Do not edit it by hand. -->

The operator reads the configuration of an ` + "`OpenTelemetryCollector`" + ` resource to create
the Kubernetes resources that some collector components need, such as Service and container
ports, RBAC rules, probes, and environment variables. It has specific support for the
components listed on this page. What it creates depends on the component.

## Components not listed here

For a receiver that is not listed, the operator still creates Service and container ports
when the receiver configuration sets a port in a top-level ` + "`endpoint`" + ` or ` + "`listen_address`" + `
field, for example ` + "`endpoint: 0.0.0.0:8126`" + `. Ports configured in nested fields, such as
` + "`tcp.listen_address`" + `, are not automatically inferred. Use the ` + "`ports`" + ` field of the
` + "`OpenTelemetryCollector`" + ` resource to expose them explicitly.

For processors, exporters, and extensions that are not listed, the operator does not create
any resources.
`

type section struct {
	title   string
	parsers []components.Parser
}

func main() {
	out := render([]section{
		{title: "Receivers", parsers: receivers.Parsers()},
		{title: "Processors", parsers: processors.Parsers()},
		{title: "Exporters", parsers: exporters.Parsers()},
		{title: "Extensions", parsers: extensions.Parsers()},
	})
	if err := os.WriteFile(outputPath, []byte(out), 0o600); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func render(sections []section) string {
	var b strings.Builder
	b.WriteString(header)
	for _, s := range sections {
		fmt.Fprintf(&b, "\n## %s\n\n", s.title)
		b.WriteString("| Component | Also accepted as |\n")
		b.WriteString("| --------- | ---------------- |\n")
		parsers := slices.Clone(s.parsers)
		slices.SortFunc(parsers, func(a, b components.Parser) int {
			return strings.Compare(a.ParserType(), b.ParserType())
		})
		for _, p := range parsers {
			aliases := slices.Sorted(slices.Values(p.ParserAliases()))
			for i, alias := range aliases {
				aliases[i] = "`" + alias + "`"
			}
			fmt.Fprintf(&b, "| `%s` | %s |\n", p.ParserType(), strings.Join(aliases, ", "))
		}
	}
	return b.String()
}
